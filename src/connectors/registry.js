export function connectorById(id) {
  return CONNECTORS.find((c) => c.id === id) || null;
}

export function connectorsByCategory(categoryId) {
  return CONNECTORS.filter((c) => c.category === categoryId);
}

export function featuredConnectors() {
  return FEATURED_CONNECTOR_IDS.map((id) => connectorById(id)).filter(Boolean);
}

/**
 * Search across name, category label, description, and capabilities.
 */
export function searchConnectors(query) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return CONNECTORS.slice();
  const catLabel = Object.fromEntries(CONNECTOR_CATEGORIES.map((c) => [c.id, c.label.toLowerCase()]));
  return CONNECTORS.filter((c) =>
    c.name.toLowerCase().includes(q)
    || c.description.toLowerCase().includes(q)
    || c.category.toLowerCase().includes(q)
    || (catLabel[c.category] || '').includes(q)
    || c.capabilities.some((cap) => cap.toLowerCase().includes(q))
  );
}

/**
 * Build SectionList sections: Featured (when no query), Connected, then
 * Available grouped by category — or flat search hits.
 */
export function connectorSections({ query, connectedIds = [] } = {}) {
  const connected = new Set(connectedIds);
  const q = String(query || '').trim();
  const pool = q ? searchConnectors(q) : CONNECTORS.slice();
  const sections = [];

  if (!q) {
    const feat = featuredConnectors().filter((c) => pool.some((p) => p.id === c.id));
    if (feat.length) sections.push({ title: 'Featured', key: 'featured', data: feat });
  }

  const connectedItems = pool.filter((c) => connected.has(c.id));
  if (connectedItems.length) {
    sections.push({ title: 'Connected', key: 'connected', data: connectedItems });
  }

  const available = pool.filter((c) => !connected.has(c.id));
  if (q) {
    if (available.length) sections.push({ title: 'Available', key: 'available', data: available });
  } else {
    for (const cat of CONNECTOR_CATEGORIES) {
      const data = available.filter((c) => c.category === cat.id);
      if (data.length) sections.push({ title: cat.label, key: cat.id, data });
    }
  }
  return sections;
}
